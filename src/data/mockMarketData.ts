// Helper to generate realistic candlestick data
function generateCandles(basePrice: number, volatility: number, count = 30): CandlePoint[] {
  const candles: CandlePoint[] = [];
  let currentPrice = basePrice * 0.96;
  const now = Date.now();
  const step = 24 * 60 * 60 * 1000; // 1 day steps

  for (let i = count; i >= 0; i--) {
    const timestamp = now - i * step;
    const date = new Date(timestamp);
    const timeStr = `${date.getMonth() + 1}/${date.getDate()}`;
    
    const change = (Math.random() - 0.48) * volatility * currentPrice;
    const open = currentPrice;
    const close = Math.max(open + change, 0.01);
    const high = Math.max(open, close) + Math.random() * volatility * currentPrice * 0.6;
    const low = Math.max(Math.min(open, close) - Math.random() * volatility * currentPrice * 0.6, 0.01);
    const volume = Math.floor(Math.random() * 5000000 + 1000000);

    candles.push({
      time: timeStr,
      timestamp,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });

    currentPrice = close;
  }
  return candles;
}

function extractSparkline(candles: CandlePoint[]): number[] {
  return candles.map(c => c.close);
}

